!!****f* m_rdmft_orbitals/rdmft_orbs_set_stars
!! NAME
!!  rdmft_orbs_set_stars
!!
!! FUNCTION
!!  Independent k-points of the orbital optimization. With use_ibz = .true. and an irreducible BZ expanded by expand_ibz, the
!!  stars of the symmetry operations (ibz_rep, ibz_conj). Otherwise the pairs {k,-k} of time reversal: the representative is
!!  the first k-point of the pair and the partner is its conjugate (a time-reversal-invariant k-point, or one without
!!  partner, is its own representative).
!!
!! INPUTS
!!  use_ibz = use the stars of the symmetry operations if they exist
!!
!! SOURCE
subroutine rdmft_orbs_set_stars(orbs,use_ibz,generic)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 logical,intent(in) :: use_ibz
 !arrays
 logical,optional,intent(in) :: generic(:)

 !Local variables-------------------------------
 !scalars
 integer :: ik,jk

! *************************************************************************

 ABI_SFREE(orbs%star_rep)
 ABI_SFREE(orbs%star_conj)
 ABI_MALLOC(orbs%star_rep,(orbs%nkpt))
 ABI_MALLOC(orbs%star_conj,(orbs%nkpt))
 do ik=1,orbs%nkpt
   orbs%star_rep(ik) = ik
   orbs%star_conj(ik) = .false.
   jk = orbs%tr_k(ik)
   if (jk > 0 .and. jk < ik) then
     orbs%star_rep(ik) = jk
     orbs%star_conj(ik) = .true.
   end if
   if (use_ibz .and. allocated(orbs%ibz_rep)) then
     ! stars of the operations for the generic k-points; the others stay time-reversal pairs
     if (present(generic)) then
       if (.not.generic(ik)) cycle
     end if
     orbs%star_rep(ik) = orbs%ibz_rep(ik)
     orbs%star_conj(ik) = orbs%ibz_conj(ik)
   end if
 end do

end subroutine rdmft_orbs_set_stars
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_sym_images
!! NAME
!!  rdmft_orbs_sym_images
!!
!! FUNCTION
!!  Action of the symmetry operations of the ground state (unitary operations and their products with time reversal) on the
!!  k-points of the mesh, kimg(k,op), and the reducible k-points (generic): those whose little group (unitary operations
!!  that leave the k-point unchanged) is trivial, or acts on the bands with diagonal matrices (the bands are only multiplied
!!  by phases, no degenerate shell forced by symmetry). The other k-points (Gamma, lines with degenerate shells, ...) stay
!!  independent and free: the symmetry is not used for them.
!!
!! SOURCE
subroutine rdmft_orbs_sym_images(orbs,tab)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(in) :: orbs
 type(rdmft_symtab_t),intent(out) :: tab

 !Local variables-------------------------------
 !scalars
 integer :: ib,ik,iop,isym,itim,jk,nb,nk,nmix,nops,npw1,nsym
 logical :: usable
 type(crystal_t) :: cryst
 !arrays
 integer :: g0(3),gmax(3),work_ngfft(18)
 real(dp) :: kp(3),dk(3)
 real(dp),allocatable :: cg2(:,:,:),work(:,:,:,:)
 complex(dpc),allocatable :: cmat(:,:),cmat2(:,:),mm(:,:)

! *************************************************************************

 cryst = orbs%hdr%get_crystal()
 nsym = cryst%nsym
 nk = orbs%nkpt
 nops = 2*nsym
 ABI_MALLOC(tab%kimg,(nk,nops))
 ABI_MALLOC(tab%ok,(nk,nops))
 ABI_MALLOC(tab%generic,(nk))
 tab%kimg = 0
 tab%ok = .false.
 do itim=0,1
   do isym=1,nsym
     iop = isym+nsym*itim
     usable = .true.
     do ik=1,nk
       kp = matmul(transpose(real(cryst%symrel(:,:,isym),dp)),orbs%kpt(:,ik))
       if (itim == 1) kp = -kp
       do jk=1,nk
         dk = orbs%kpt(:,jk)-kp
         if (maxval(abs(dk-anint(dk))) < 1.0e-6_dp) then
           tab%kimg(ik,iop) = jk
           exit
         end if
       end do
       if (tab%kimg(ik,iop) == 0) then
         usable = .false.
         exit
       end if
     end do
     if (.not.usable) then
       tab%kimg(:,iop) = 0
     else
       tab%nops = tab%nops+1
     end if
   end do
 end do
 !A k-point is reducible if its little group does not mix its bands: the identity is the only unitary operation that leaves
 !it unchanged (generic k-point), or every such operation acts on the bands with a diagonal matrix <psi_a|S psi_b> (no
 !degenerate shell forced by symmetry, the bands are only multiplied by phases)
 gmax = 2*maxval(abs(orbs%kg))+1
 call ngfft_seq(work_ngfft,gmax)
 ABI_MALLOC(work,(2,work_ngfft(4),work_ngfft(5),work_ngfft(6)))
 work = zero
 nmix = 0
 do ik=1,nk
   tab%generic(ik) = .true.
   do isym=2,nsym
     iop = isym
     if (tab%kimg(1,iop) == 0) cycle
     if (tab%kimg(ik,iop) /= ik) cycle
     nb = orbs%nband(ik,1)
     npw1 = orbs%npw(ik)
     kp = matmul(transpose(real(cryst%symrel(:,:,isym),dp)),orbs%kpt(:,ik))
     g0 = nint(orbs%kpt(:,ik)-kp)
     ABI_MALLOC(cg2,(2,npw1*orbs%nspinor,nb))
     call cgtk_rotate(cryst,orbs%kpt(:,ik),isym,0,g0,orbs%nspinor,nb,npw1,orbs%kg(:,1:npw1,ik),npw1,&
                      orbs%kg(:,1:npw1,ik),1,1,orbs%cg(:,1:npw1*orbs%nspinor,1:nb,ik,1),cg2,work_ngfft,work)
     ABI_MALLOC(cmat,(npw1*orbs%nspinor,nb))
     ABI_MALLOC(cmat2,(npw1*orbs%nspinor,nb))
     ABI_MALLOC(mm,(nb,nb))
     cmat = cmplx(orbs%cg(1,1:npw1*orbs%nspinor,1:nb,ik,1),orbs%cg(2,1:npw1*orbs%nspinor,1:nb,ik,1),kind=dpc)
     cmat2 = cmplx(cg2(1,:,:),cg2(2,:,:),kind=dpc)
     mm = matmul(transpose(conjg(cmat)),cmat2)
     do ib=1,nb
       mm(ib,ib) = czero
     end do
     if (maxval(abs(mm)) > 1.0e-4_dp) tab%generic(ik) = .false.
     ABI_FREE(cg2)
     ABI_FREE(cmat)
     ABI_FREE(cmat2)
     ABI_FREE(mm)
     if (.not.tab%generic(ik)) exit
   end do
   if (.not.tab%generic(ik)) nmix = nmix+1
 end do
 ABI_FREE(work)
 call cryst%free()

end subroutine rdmft_orbs_sym_images
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_build_symtab
!! NAME
!!  rdmft_orbs_build_symtab
!!
!! FUNCTION
!!  Build the classes of ordered pairs of k-points under the symmetry operations of the ground state (spatial operations and
!!  their products with time reversal) that map the orbitals of generic k-points onto the orbitals of the image k-points
!!  (same band index, common phase), within the stars used by the orbital optimization (star_rep, star_conj): the image
!!  of a star keeps the covariance during the optimization. The pairs that contain another k-point are computed explicitly.
!!  Needs sym_images and set_stars before.
!!
!! INPUTS
!!  tol = largest accepted deviation of the covariance: 1-|<psi'_n|S psi_n>| and the difference between the overlaps of the bands
!!
!! OUTPUT
!!  tab = the classes
!!  nok, ntot = number of covariant (k, operation) couples, and of couples where the operation maps k into the mesh
!!  devmax = largest deviation among the accepted couples
!!
!! SOURCE
subroutine rdmft_orbs_build_symtab(orbs,tab,tol,nok,ntot,devmax)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(in) :: orbs
 type(rdmft_symtab_t),intent(inout) :: tab
 real(dp),intent(in) :: tol
 integer,intent(out) :: nok,ntot
 real(dp),intent(out) :: devmax

 !Local variables-------------------------------
 !scalars
 integer :: a,b,c,ia,ib,id,id2,ik,imem,iop,isym,itim,jk,nb,nk,nops,npw1,npw2,nsym,r1,r2
 real(dp) :: dev,ov(2),ov0(2)
 type(crystal_t) :: cryst
 !arrays
 integer :: g0(3),gmax(3),work_ngfft(18)
 integer,allocatable :: parent(:),cnt(:),croot(:)
 real(dp) :: kp(3)
 real(dp),allocatable :: cg2(:,:,:),work(:,:,:,:)

! *************************************************************************

 cryst = orbs%hdr%get_crystal()
 nsym = cryst%nsym
 nk = orbs%nkpt
 nops = 2*nsym
 tab%ok = .false.
 nok = 0
 ntot = 0
 devmax = zero

 gmax = 2*maxval(abs(orbs%kg))+1
 call ngfft_seq(work_ngfft,gmax)
 ABI_MALLOC(work,(2,work_ngfft(4),work_ngfft(5),work_ngfft(6)))
 work = zero

 do itim=0,1
   do isym=1,nsym
     iop = isym+nsym*itim
     if (tab%kimg(1,iop) == 0) cycle
     do ik=1,nk
       jk = tab%kimg(ik,iop)
       ntot = ntot+1
       if (.not.tab%generic(ik)) cycle
       !Only inside a star of the orbital optimization, with the conjugation of the rotation kept (unitary operation) or
       !changed (antiunitary one)
       if (orbs%star_rep(ik) /= orbs%star_rep(jk)) cycle
       if ((orbs%star_conj(ik) .neqv. orbs%star_conj(jk)) .neqv. (itim == 1)) cycle
       nb = orbs%nband(ik,1)
       if (orbs%nband(jk,1) /= nb .or. orbs%npw(jk) /= orbs%npw(ik)) cycle
       npw1 = orbs%npw(ik)
       npw2 = orbs%npw(jk)
       kp = matmul(transpose(real(cryst%symrel(:,:,isym),dp)),orbs%kpt(:,ik))
       if (itim == 1) kp = -kp
       g0 = nint(orbs%kpt(:,jk)-kp)
       ABI_MALLOC(cg2,(2,npw2*orbs%nspinor,nb))
       call cgtk_rotate(cryst,orbs%kpt(:,ik),isym,itim,g0,orbs%nspinor,nb,npw1,orbs%kg(:,1:npw1,ik),npw2,&
                        orbs%kg(:,1:npw2,jk),1,1,orbs%cg(:,1:npw1*orbs%nspinor,1:nb,ik,1),cg2,work_ngfft,work)
       !Band by band overlap <psi(Sk)_n| S psi(k)_n>: the same complex number for all the bands (modulus one, common
       !phase), so that a common rotation of the bands of the star keeps the orbitals covariant
       dev = zero
       do ib=1,nb
         ov(1) = sum(orbs%cg(1,1:npw2*orbs%nspinor,ib,jk,1)*cg2(1,:,ib)+orbs%cg(2,1:npw2*orbs%nspinor,ib,jk,1)*cg2(2,:,ib))
         ov(2) = sum(orbs%cg(1,1:npw2*orbs%nspinor,ib,jk,1)*cg2(2,:,ib)-orbs%cg(2,1:npw2*orbs%nspinor,ib,jk,1)*cg2(1,:,ib))
         if (ib == 1) ov0 = ov
         dev = max(dev,max(one-sqrt(ov(1)**2+ov(2)**2),zero),sqrt((ov(1)-ov0(1))**2+(ov(2)-ov0(2))**2))
       end do
       ABI_FREE(cg2)
       if (dev < tol) then
         tab%ok(ik,iop) = .true.
         nok = nok+1
         devmax = max(devmax,dev)
       end if
     end do
   end do
 end do
 ABI_FREE(work)

 !Classes of ordered pairs of k-points: union of (k,k') and (S k, S k') for the covariant operations
 ABI_MALLOC(parent,(nk*nk))
 do id=1,nk*nk
   parent(id) = id
 end do
 do iop=1,nops
   if (tab%kimg(1,iop) == 0) cycle
   do a=1,nk
     if (.not.tab%ok(a,iop)) cycle
     do b=1,nk
       if (.not.tab%ok(b,iop)) cycle
       id = (a-1)*nk+b
       id2 = (tab%kimg(a,iop)-1)*nk+tab%kimg(b,iop)
       r1 = id
       do while (parent(r1) /= r1)
         parent(r1) = parent(parent(r1))
         r1 = parent(r1)
       end do
       r2 = id2
       do while (parent(r2) /= r2)
         parent(r2) = parent(parent(r2))
         r2 = parent(r2)
       end do
       if (r1 /= r2) then
         if (r1 < r2) then
           parent(r2) = r1
         else
           parent(r1) = r2
         end if
       end if
     end do
   end do
 end do
 !The root is the smallest pair of the class (lexicographic order): class numbers in increasing order of the roots
 ABI_MALLOC(croot,(nk*nk))
 croot = 0
 ABI_MALLOC(tab%cls,(nk,nk))
 tab%ncls = 0
 do id=1,nk*nk
   r1 = id
   do while (parent(r1) /= r1)
     r1 = parent(r1)
   end do
   if (croot(r1) == 0) then
     tab%ncls = tab%ncls+1
     croot(r1) = tab%ncls
   end if
   ia = (id-1)/nk+1
   ib = id-(ia-1)*nk
   tab%cls(ia,ib) = croot(r1)
 end do
 ABI_MALLOC(tab%rep,(2,tab%ncls))
 ABI_MALLOC(tab%mptr,(tab%ncls+1))
 ABI_MALLOC(tab%mem,(2,nk*nk))
 ABI_MALLOC(tab%use,(tab%ncls))
 ABI_MALLOC(tab%selft,(tab%ncls))
 ABI_MALLOC(cnt,(tab%ncls))
 cnt = 0
 do a=1,nk
   do b=1,nk
     cnt(tab%cls(a,b)) = cnt(tab%cls(a,b))+1
   end do
 end do
 tab%mptr(1) = 1
 do c=1,tab%ncls
   tab%mptr(c+1) = tab%mptr(c)+cnt(c)
 end do
 cnt = 0
 tab%rep = 0
 do a=1,nk
   do b=1,nk
     c = tab%cls(a,b)
     if (tab%rep(1,c) == 0) tab%rep(:,c) = [a,b]
     imem = tab%mptr(c)+cnt(c)
     tab%mem(:,imem) = [a,b]
     cnt(c) = cnt(c)+1
   end do
 end do
 do c=1,tab%ncls
   a = tab%rep(1,c)
   b = tab%rep(2,c)
   tab%selft(c) = (tab%cls(b,a) == c)
   tab%use(c) = (c <= tab%cls(b,a))
 end do
 ABI_FREE(parent)
 ABI_FREE(croot)
 ABI_FREE(cnt)
 call cryst%free()

end subroutine rdmft_orbs_build_symtab
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_complete_time_reversal
!! NAME
!!  rdmft_orbs_complete_time_reversal
!!
!! FUNCTION
!!  Complete the k-point mesh so that it contains -k for every k. For a Monkhorst-Pack mesh either all the
!!  k-points have a partner or none (a mixed mesh is refused). The orbital of the added point -k is the complex
!!  conjugate of the one at k: c_{n,-k}(G) = conjg(c_{n,k}(-G)), i.e. the plane-wave list is -kg and the coefficients
!!  are conjugated; energies and occupations are the same. The mesh then has 2N points of weight 1/(2N).
!!
!! OUTPUT
!!  nadded = number of k-points added (0 if the mesh was already closed)
!!
!! SOURCE
subroutine rdmft_orbs_complete_time_reversal(orbs,nadded)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: nadded

 !Local variables-------------------------------
 !scalars
 integer :: ik,j,nk1,nk2
 !arrays
 integer,allocatable :: nband(:,:),npw(:),kg(:,:,:),tr_new(:),src(:),srep_new(:)
 real(dp),allocatable :: kpt(:,:),wtk(:),eig(:,:,:),occ(:,:,:),cg(:,:,:,:,:)
 logical,allocatable :: added(:),sconj_new(:)

! *************************************************************************

 nadded = 0
 nk1 = orbs%nkpt
 ! k-points whose -k is not in the mesh (the time-reversal-invariant ones, tr_k = k, are their own partners)
 nadded = count(orbs%tr_k(:) == 0)
 if (nadded == 0) return
 if (any(orbs%tr_k(:) > 0 .and. orbs%tr_k(:) /= [(ik,ik=1,nk1)])) then
   nadded = 0
   ABI_ERROR('RDMFT: the k-point mesh has some k-points with -k and some without, the completion is not supported.')
 end if

 nk2 = nk1+nadded
 ABI_MALLOC(src,(nadded))
 j = 0
 do ik=1,nk1
   if (orbs%tr_k(ik) == 0) then
     j = j+1
     src(j) = ik
   end if
 end do
 ABI_MALLOC(nband,(nk2,orbs%nsppol))
 ABI_MALLOC(npw,(nk2))
 ABI_MALLOC(kg,(3,orbs%mpw,nk2))
 ABI_MALLOC(kpt,(3,nk2))
 ABI_MALLOC(wtk,(nk2))
 ABI_MALLOC(eig,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(occ,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(cg,(2,orbs%mpw*orbs%nspinor,orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(added,(nk2))
 ABI_MALLOC(tr_new,(nk2))

 nband(1:nk1,:) = orbs%nband
 npw(1:nk1) = orbs%npw
 kg(:,:,1:nk1) = orbs%kg
 kpt(:,1:nk1) = orbs%kpt
 eig(:,1:nk1,:) = orbs%eig
 occ(:,1:nk1,:) = orbs%occ
 cg(:,:,:,1:nk1,:) = orbs%cg
 added(1:nk1) = .false.
 tr_new(1:nk1) = orbs%tr_k
 do j=1,nadded
   ik = src(j)
   nband(nk1+j,:) = orbs%nband(ik,:)
   npw(nk1+j) = orbs%npw(ik)
   kg(:,:,nk1+j) = -orbs%kg(:,:,ik)
   kpt(:,nk1+j) = -orbs%kpt(:,ik)
   eig(:,nk1+j,:) = orbs%eig(:,ik,:)
   occ(:,nk1+j,:) = orbs%occ(:,ik,:)
   cg(1,:,:,nk1+j,:) = orbs%cg(1,:,:,ik,:)
   cg(2,:,:,nk1+j,:) = -orbs%cg(2,:,:,ik,:)
   added(nk1+j) = .true.
   tr_new(ik) = nk1+j
   tr_new(nk1+j) = ik
 end do
 ! Uniform weights: the pairs (k,-k) have the same weight, and so do the time-reversal-invariant points
 wtk = one/real(nk2,dp)

 call move_alloc(nband,orbs%nband)
 call move_alloc(npw,orbs%npw)
 call move_alloc(kg,orbs%kg)
 call move_alloc(kpt,orbs%kpt)
 call move_alloc(wtk,orbs%wtk)
 call move_alloc(eig,orbs%eig)
 call move_alloc(occ,orbs%occ)
 call move_alloc(cg,orbs%cg)
 call move_alloc(added,orbs%added)
 call move_alloc(tr_new,orbs%tr_k)
 !Stars of the symmetry operations (expand_ibz): the added k-point is the time-reversed image of its source
 if (allocated(orbs%ibz_rep)) then
   ABI_MALLOC(srep_new,(nk2))
   ABI_MALLOC(sconj_new,(nk2))
   srep_new(1:nk1) = orbs%ibz_rep
   sconj_new(1:nk1) = orbs%ibz_conj
   do j=1,nadded
     srep_new(nk1+j) = orbs%ibz_rep(src(j))
     sconj_new(nk1+j) = .not.orbs%ibz_conj(src(j))
   end do
   call move_alloc(srep_new,orbs%ibz_rep)
   call move_alloc(sconj_new,orbs%ibz_conj)
 end if
 ABI_FREE(src)
 orbs%nkpt = nk2

end subroutine rdmft_orbs_complete_time_reversal
!!***

!!****f* m_rdmft_orbitals/rdmft_rot_matrix
!! NAME
!!  rdmft_rot_matrix
!!
!! FUNCTION
!!  Unitary matrix U = exp(kappa) of a rotation of two orbitals p and q of the same k-point, in the basis (p,q):
!!   - real direction (imag=.false.): kappa_pq = theta, kappa_qp = -theta, U = [[cos, sin],[-sin, cos]]
!!   - imaginary direction (imag=.true.): kappa_pq = kappa_qp = i theta, U = [[cos, i sin],[i sin, cos]]
!!  The rotated orbitals are psi'_j = sum_i psi_i U_ij. With conj_rot, the complex conjugate of U (the rotation of the
!!  time-reversed orbitals at -k).
!!
!! SOURCE
function rdmft_rot_matrix(theta,imag,conj_rot) result(umat)

 !Arguments ------------------------------------
 !scalars
 real(dp),intent(in) :: theta
 logical,intent(in) :: imag,conj_rot
 complex(dpc) :: umat(2,2)

 !Local variables-------------------------------
 !scalars
 real(dp) :: c,s

! *************************************************************************

 c = cos(theta)
 s = sin(theta)
 umat = czero
 umat(1,1) = cmplx(c,zero,kind=dpc)
 umat(2,2) = cmplx(c,zero,kind=dpc)
 if (imag) then
   umat(1,2) = cmplx(zero,s,kind=dpc)
   umat(2,1) = cmplx(zero,s,kind=dpc)
 else
   umat(1,2) = cmplx(s,zero,kind=dpc)
   umat(2,1) = cmplx(-s,zero,kind=dpc)
 end if
 if (conj_rot) umat = conjg(umat)

end function rdmft_rot_matrix
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_rotate_pair
!! NAME
!!  rdmft_orbs_rotate_pair
!!
!! FUNCTION
!!  Rotate the bands ib and jb of the k-point ik with the matrix U of rdmft_rot_matrix:
!!  psi'_ib = U_11 psi_ib + U_21 psi_jb, psi'_jb = U_12 psi_ib + U_22 psi_jb. The rotation mixes only states of
!!  the same k-point, so the Bloch character is kept.
!!
!! INPUTS
!!  ik, ib, jb = k-point and bands
!!  umat(2,2) = rotation matrix
!!
!! SOURCE
subroutine rdmft_orbs_rotate_pair(orbs,ik,ib,jb,umat)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(in) :: ik,ib,jb
 !arrays
 complex(dpc),intent(in) :: umat(2,2)

 !Local variables-------------------------------
 !scalars
 integer :: ig,npwso
 complex(dpc) :: cp,cq

! *************************************************************************

 npwso = orbs%npw(ik)*orbs%nspinor
 do ig=1,npwso
   cp = cmplx(orbs%cg(1,ig,ib,ik,1),orbs%cg(2,ig,ib,ik,1),kind=dpc)
   cq = cmplx(orbs%cg(1,ig,jb,ik,1),orbs%cg(2,ig,jb,ik,1),kind=dpc)
   orbs%cg(1,ig,ib,ik,1) = real(cp*umat(1,1)+cq*umat(2,1),dp)
   orbs%cg(2,ig,ib,ik,1) = aimag(cp*umat(1,1)+cq*umat(2,1))
   orbs%cg(1,ig,jb,ik,1) = real(cp*umat(1,2)+cq*umat(2,2),dp)
   orbs%cg(2,ig,jb,ik,1) = aimag(cp*umat(1,2)+cq*umat(2,2))
 end do

end subroutine rdmft_orbs_rotate_pair
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_rotate_k
!! NAME
!!  rdmft_orbs_rotate_k
!!
!! FUNCTION
!!  Rotate all the bands of the k-point ik with the unitary matrix U: psi'_j = sum_i psi_i U_ij.
!!  The rotation mixes only states of the same k-point, so the Bloch character is kept.
!!
!! INPUTS
!!  ik = k-point
!!  umat(nband,nband) = unitary matrix
!!
!! SOURCE
subroutine rdmft_orbs_rotate_k(orbs,ik,umat)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(in) :: ik
 !arrays
 complex(dpc),intent(in) :: umat(:,:)

 !Local variables-------------------------------
 !scalars
 integer :: ib,ig,jb,nb,npwso
 !arrays
 complex(dpc),allocatable :: cold(:,:),cnew(:)

! *************************************************************************

 nb = orbs%nband(ik,1)
 npwso = orbs%npw(ik)*orbs%nspinor
 ABI_MALLOC(cold,(nb,npwso))
 ABI_MALLOC(cnew,(nb))
 do ib=1,nb
   do ig=1,npwso
     cold(ib,ig) = cmplx(orbs%cg(1,ig,ib,ik,1),orbs%cg(2,ig,ib,ik,1),kind=dpc)
   end do
 end do
 do ig=1,npwso
   do jb=1,nb
     cnew(jb) = czero
     do ib=1,nb
       cnew(jb) = cnew(jb)+cold(ib,ig)*umat(ib,jb)
     end do
   end do
   do jb=1,nb
     orbs%cg(1,ig,jb,ik,1) = real(cnew(jb),dp)
     orbs%cg(2,ig,jb,ik,1) = aimag(cnew(jb))
   end do
 end do
 ABI_FREE(cold)
 ABI_FREE(cnew)

end subroutine rdmft_orbs_rotate_k
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_tr_alignment
!! NAME
!!  rdmft_orbs_tr_alignment
!!
!! FUNCTION
!!  For every k-point with its partner -k in the mesh (tr_k>0, possibly itself), compare the orbital n at -k with the
!!  time-reversed orbital n of k, Theta psi_{nk}: c'(G') = conjg(c_{nk}(G)) with G' = -G - R, R = k + (-k).
!!  The overlap |<psi_{n,-k}|Theta psi_{nk}>| is 1 when the orbital at -k is the conjugate of the one at k up to a
!!  phase, which is the pairing assumed when the occupations of k and -k are tied (the energy functionals themselves
!!  only use K_pq, which does not depend on these phases).
!!
!! OUTPUT
!!  maxdev = largest 1-|overlap| over the bands and k-points having a partner
!!  ik_worst, ib_worst = where it is found (0 if no k-point has a partner)
!!
!! SOURCE
subroutine rdmft_orbs_tr_alignment(orbs,maxdev,ik_worst,ib_worst)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(in) :: orbs
 real(dp),intent(out) :: maxdev
 integer,intent(out) :: ik_worst,ib_worst

 !Local variables-------------------------------
 !scalars
 integer :: ib,ig,ik,jk,m,n1,idx,nb
 real(dp) :: dev
 complex(dpc) :: ovlp
 !arrays
 integer :: rr(3)
 integer,allocatable :: lookup(:)

! *************************************************************************

 maxdev = zero
 ik_worst = 0
 ib_worst = 0
 m = max(maxval(abs(orbs%kg)),1)+2
 n1 = 2*m+1
 ABI_MALLOC(lookup,(n1**3))
 do ik=1,orbs%nkpt
   jk = orbs%tr_k(ik)
   if (jk <= 0) cycle
   nb = orbs%nband(ik,1)
   ! Index of the plane waves of -k
   lookup = 0
   do ig=1,orbs%npw(jk)
     lookup(1+(orbs%kg(1,ig,jk)+m)+n1*((orbs%kg(2,ig,jk)+m)+n1*(orbs%kg(3,ig,jk)+m))) = ig
   end do
   rr = nint(orbs%kpt(:,ik)+orbs%kpt(:,jk))
   do ib=1,nb
     ovlp = czero
     do ig=1,orbs%npw(ik)
       idx = lookup(1+(-orbs%kg(1,ig,ik)-rr(1)+m)+n1*((-orbs%kg(2,ig,ik)-rr(2)+m)+n1*(-orbs%kg(3,ig,ik)-rr(3)+m)))
       if (idx == 0) cycle
       ! <psi_{n,-k}|Theta psi_{nk}> = sum_G' conjg(c_{n,-k}(G')) conjg(c_{nk}(G))
       ovlp = ovlp+conjg(cmplx(orbs%cg(1,idx,ib,jk,1),orbs%cg(2,idx,ib,jk,1),kind=dpc))* &
                   conjg(cmplx(orbs%cg(1,ig,ib,ik,1),orbs%cg(2,ig,ib,ik,1),kind=dpc))
     end do
     dev = one-real(ovlp,dp)
     if (dev > maxdev) then
       maxdev = dev; ik_worst = ik; ib_worst = ib
     end if
   end do
 end do
 ABI_FREE(lookup)

end subroutine rdmft_orbs_tr_alignment
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_check_orthonormality
!! NAME
!!  rdmft_orbs_check_orthonormality
!!
!! FUNCTION
!!  Compute the maximum over k-points of |<psi_nk|psi_mk> - delta_nm|.
!!
!! OUTPUT
!!  maxdev = maximum deviation from orthonormality
!!
!! SOURCE
function rdmft_orbs_check_orthonormality(orbs) result(maxdev)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(in) :: orbs
 real(dp) :: maxdev

 !Local variables-------------------------------
 !scalars
 integer :: ib,ik,isppol,jb,nb,npwso
 complex(dpc) :: ovlp

! *************************************************************************

 maxdev = zero
 do isppol=1,orbs%nsppol
   do ik=1,orbs%nkpt
     nb = orbs%nband(ik,isppol)
     npwso = orbs%npw(ik)*orbs%nspinor
     do ib=1,nb
       do jb=1,ib
         ovlp = sum(cmplx(orbs%cg(1,1:npwso,ib,ik,isppol),-orbs%cg(2,1:npwso,ib,ik,isppol),kind=dpc)* &
                    cmplx(orbs%cg(1,1:npwso,jb,ik,isppol), orbs%cg(2,1:npwso,jb,ik,isppol),kind=dpc))
         if (ib == jb) ovlp = ovlp - cone
         maxdev = max(maxdev,abs(ovlp))
       end do
     end do
   end do
 end do

end function rdmft_orbs_check_orthonormality
