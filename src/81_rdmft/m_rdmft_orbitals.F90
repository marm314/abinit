#if defined HAVE_CONFIG_H
#include "config.h"
#endif

#include "abi_common.h"

module m_rdmft_orbitals

 use defs_basis
 use m_abicore
 use m_errors
 use m_xmpi
 use m_hdr
 use m_wfk

 use m_geometry,   only : metric
 use m_io_tools,   only : iomode_from_fname, get_unit
 use m_specialmsg, only : wrtout

 implicit none

 private
!!***

!!****t* m_rdmft_orbitals/rdmft_orbs_t
!! NAME
!! rdmft_orbs_t
!!
!! FUNCTION
!!  Ground-state Bloch orbitals read from a WFK file.
!!
!! SOURCE

 type,public :: rdmft_orbs_t

   integer :: nkpt = 0
   ! Number of k-points.

   integer :: nsppol = 0
   ! Number of spin polarizations.

   integer :: nspinor = 0
   ! Number of spinor components.

   integer :: mband = 0
   ! Maximum number of bands over k-points.

   integer :: mpw = 0
   ! Maximum number of plane waves over k-points.

   real(dp) :: nelect = zero
   ! Number of electrons.

   real(dp) :: ucvol = zero
   ! Volume of the unit cell (Bohr^3).

   real(dp) :: rprimd(3,3) = zero
   ! Real space primitive translations (Bohr).

   real(dp) :: gmet(3,3) = zero
   ! Metric tensor in reciprocal space (Bohr^-2).

   integer,allocatable :: nband(:,:)
   ! nband(nkpt,nsppol)
   ! Number of bands at each k-point and spin.

   integer,allocatable :: npw(:)
   ! npw(nkpt)
   ! Number of plane waves at each k-point.

   integer,allocatable :: kg(:,:,:)
   ! kg(3,mpw,nkpt)
   ! Reduced coordinates of the plane waves at each k-point.

   real(dp),allocatable :: kpt(:,:)
   ! kpt(3,nkpt)
   ! Reduced coordinates of the k-points.

   real(dp),allocatable :: wtk(:)
   ! wtk(nkpt)
   ! Weights of the k-points (normalized to one).

   real(dp),allocatable :: eig(:,:,:)
   ! eig(mband,nkpt,nsppol)
   ! Eigenvalues (Hartree).

   real(dp),allocatable :: occ(:,:,:)
   ! occ(mband,nkpt,nsppol)
   ! Occupation numbers of the ground-state calculation (between 0 and 2/nsppol/nspinor).

   real(dp),allocatable :: cg(:,:,:,:,:)
   ! cg(2,mpw*nspinor,mband,nkpt,nsppol)
   ! Plane-wave coefficients, normalized to one for each band.

   integer,allocatable :: tr_k(:)
   ! tr_k(nkpt)
   ! Index of the k-point equal to -k modulo a reciprocal lattice vector (itself for the time-reversal-invariant
   ! k-points), 0 if -k is not in the mesh.

   logical,allocatable :: added(:)
   ! added(nkpt)
   ! True for the k-points generated by time reversal (complete_time_reversal).

 contains

   procedure :: free => rdmft_orbs_free
   ! Free memory.

   procedure :: read_wfk => rdmft_orbs_read_wfk
   ! Read the orbitals from a WFK file.

   procedure :: check_orthonormality => rdmft_orbs_check_orthonormality
   ! Compute the maximum deviation from orthonormality.

   procedure :: find_tr_partners => rdmft_orbs_find_tr_partners
   ! Find the k-point -k of every k-point of the mesh.

   procedure :: complete_time_reversal => rdmft_orbs_complete_time_reversal
   ! Add the missing -k points, with the time-reversed orbitals.

   procedure :: rotate_pair => rdmft_orbs_rotate_pair
   ! Rotate two bands of one k-point.

 end type rdmft_orbs_t
!!***

 public :: rdmft_rot_matrix
!!***

contains
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_free
!! NAME
!!  rdmft_orbs_free
!!
!! FUNCTION
!!  Free the memory of the orbitals.
!!
!! SOURCE
subroutine rdmft_orbs_free(orbs)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs

! *************************************************************************

 ABI_SFREE(orbs%nband)
 ABI_SFREE(orbs%npw)
 ABI_SFREE(orbs%kg)
 ABI_SFREE(orbs%kpt)
 ABI_SFREE(orbs%wtk)
 ABI_SFREE(orbs%eig)
 ABI_SFREE(orbs%occ)
 ABI_SFREE(orbs%cg)
 ABI_SFREE(orbs%tr_k)
 ABI_SFREE(orbs%added)

 orbs%nkpt = 0
 orbs%nsppol = 0
 orbs%nspinor = 0
 orbs%mband = 0
 orbs%mpw = 0
 orbs%nelect = zero
 orbs%ucvol = zero
 orbs%rprimd = zero
 orbs%gmet = zero

end subroutine rdmft_orbs_free
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_read_wfk
!! NAME
!!  rdmft_orbs_read_wfk
!!
!! FUNCTION
!!  Read the orbitals, eigenvalues and occupations of all k-points from a WFK file.
!!
!! INPUTS
!!  wfk_path = path of the WFK file (Fortran or netcdf format)
!!
!! OUTPUT
!!  orbs <type(rdmft_orbs_t)> = the orbitals (allocated here)
!!
!! SOURCE
subroutine rdmft_orbs_read_wfk(orbs,wfk_path)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 character(len=*),intent(in) :: wfk_path

 !Local variables-------------------------------
 !scalars
 integer,parameter :: formeig0=0
 integer :: ik,isppol,nb,npw_k,sc_mode
 character(len=500) :: msg
 type(hdr_type) :: hdr
 type(wfk_t) :: wfk
 !arrays
 integer :: band_block(2)
 integer,allocatable :: kg_k(:,:)
 real(dp) :: gprimd(3,3),rmet(3,3)
 real(dp),allocatable :: cg_k(:,:),eig_k(:),occ_k(:)

! *************************************************************************

 call orbs%free()

 call wfk%open_read(wfk_path,formeig0,iomode_from_fname(wfk_path),get_unit(),xmpi_comm_self,hdr_out=hdr)

 if (hdr%usepaw /= 0) then
   ABI_ERROR('RDMFT: PAW is not yet supported.')
 end if
 if (hdr%nspinor /= 1) then
   ABI_ERROR('RDMFT: nspinor=1 is required.')
 end if
 if (hdr%nsppol /= 1) then
   ABI_ERROR('RDMFT: nsppol=1 is required (closed-shell).')
 end if
 if (any(hdr%istwfk(:) /= 1)) then
   ABI_ERROR('RDMFT: istwfk=1 is required at all k-points (use istwfk *1 in the ground-state calculation).')
 end if

 orbs%nkpt = hdr%nkpt
 orbs%nsppol = hdr%nsppol
 orbs%nspinor = hdr%nspinor
 orbs%mband = maxval(hdr%nband)
 orbs%mpw = maxval(hdr%npwarr)
 orbs%nelect = hdr%nelect
 orbs%rprimd(:,:) = hdr%rprimd(:,:)
 call metric(orbs%gmet,gprimd,-1,rmet,orbs%rprimd,orbs%ucvol)

 ABI_MALLOC(orbs%nband,(orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%npw,(orbs%nkpt))
 ABI_MALLOC(orbs%kg,(3,orbs%mpw,orbs%nkpt))
 ABI_MALLOC(orbs%kpt,(3,orbs%nkpt))
 ABI_MALLOC(orbs%wtk,(orbs%nkpt))
 ABI_MALLOC(orbs%eig,(orbs%mband,orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%occ,(orbs%mband,orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%cg,(2,orbs%mpw*orbs%nspinor,orbs%mband,orbs%nkpt,orbs%nsppol))

 orbs%nband = 0
 orbs%kg = 0
 orbs%eig = zero
 orbs%occ = zero
 orbs%cg = zero
 orbs%npw(:) = hdr%npwarr(:)
 orbs%kpt(:,:) = hdr%kptns(:,:)
 orbs%wtk(:) = hdr%wtk(:)/sum(hdr%wtk)

 sc_mode = xmpio_single
 do isppol=1,orbs%nsppol
   do ik=1,orbs%nkpt
     nb = hdr%nband(ik+(isppol-1)*orbs%nkpt)
     orbs%nband(ik,isppol) = nb
     npw_k = orbs%npw(ik)
     band_block = [1,nb]

     ABI_MALLOC(kg_k,(3,npw_k))
     ABI_MALLOC(cg_k,(2,npw_k*orbs%nspinor*nb))
     ABI_MALLOC(eig_k,(wfk%mband))
     ABI_MALLOC(occ_k,(wfk%mband))

     call wfk%read_band_block(band_block,ik,isppol,sc_mode,kg_k=kg_k,cg_k=cg_k,eig_k=eig_k,occ_k=occ_k)

     orbs%kg(:,1:npw_k,ik) = kg_k(:,:)
     orbs%cg(:,1:npw_k*orbs%nspinor,1:nb,ik,isppol) = reshape(cg_k,[2,npw_k*orbs%nspinor,nb])
     orbs%eig(1:nb,ik,isppol) = eig_k(1:nb)
     orbs%occ(1:nb,ik,isppol) = occ_k(1:nb)

     ABI_FREE(kg_k)
     ABI_FREE(cg_k)
     ABI_FREE(eig_k)
     ABI_FREE(occ_k)
   end do
 end do

 call wfk%close()
 call hdr%free()

 ABI_MALLOC(orbs%added,(orbs%nkpt))
 orbs%added = .false.
 call orbs%find_tr_partners()

 write(msg,'(3a,i0,a,i0,a,i0,a,i0,a)') ' RDMFT: orbitals read from ',trim(wfk_path),ch10,&
   orbs%nkpt,' k-points, ',orbs%mband,' bands, up to ',orbs%mpw,' plane waves, nelect = ',nint(orbs%nelect),ch10
 call wrtout([ab_out,std_out],msg)

end subroutine rdmft_orbs_read_wfk
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_find_tr_partners
!! NAME
!!  rdmft_orbs_find_tr_partners
!!
!! FUNCTION
!!  Find for every k-point the k-point equal to -k modulo a reciprocal lattice vector (tr_k, 0 if absent).
!!
!! SOURCE
subroutine rdmft_orbs_find_tr_partners(orbs)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs

 !Local variables-------------------------------
 !scalars
 integer :: ik,jk
 !arrays
 real(dp) :: kt(3)

! *************************************************************************

 ABI_SFREE(orbs%tr_k)
 ABI_MALLOC(orbs%tr_k,(orbs%nkpt))
 orbs%tr_k = 0
 do ik=1,orbs%nkpt
   do jk=1,orbs%nkpt
     kt(:) = orbs%kpt(:,ik)+orbs%kpt(:,jk)
     if (maxval(abs(kt(:)-anint(kt(:)))) < 1.0e-6_dp) then
       orbs%tr_k(ik) = jk
       exit
     end if
   end do
 end do

end subroutine rdmft_orbs_find_tr_partners
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_complete_time_reversal
!! NAME
!!  rdmft_orbs_complete_time_reversal
!!
!! FUNCTION
!!  Complete the k-point mesh so that it contains -k for every k. For a Monkhorst-Pack mesh either all the
!!  k-points have a partner or none (a mixed mesh is refused). The orbital of the added point -k is the complex
!!  conjugate of the one at k: c_{n,-k}(G) = conjg(c_{n,k}(-G)), i.e. the plane-wave list is -kg and the coefficients
!!  are conjugated; energies and occupations are the same. The mesh then has 2N points of weight 1/(2N).
!!
!! OUTPUT
!!  nadded = number of k-points added (0 if the mesh was already closed)
!!
!! SOURCE
subroutine rdmft_orbs_complete_time_reversal(orbs,nadded)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: nadded

 !Local variables-------------------------------
 !scalars
 integer :: ik,nk1,nk2
 !arrays
 integer,allocatable :: nband(:,:),npw(:),kg(:,:,:),tr_new(:)
 real(dp),allocatable :: kpt(:,:),wtk(:),eig(:,:,:),occ(:,:,:),cg(:,:,:,:,:)
 logical,allocatable :: added(:)

! *************************************************************************

 nadded = 0
 nk1 = orbs%nkpt
 if (all(orbs%tr_k(:) > 0)) return
 if (any(orbs%tr_k(:) > 0)) then
   ABI_ERROR('RDMFT: the k-point mesh has some k-points with -k and some without, the completion is not supported.')
 end if

 nk2 = 2*nk1
 ABI_MALLOC(nband,(nk2,orbs%nsppol))
 ABI_MALLOC(npw,(nk2))
 ABI_MALLOC(kg,(3,orbs%mpw,nk2))
 ABI_MALLOC(kpt,(3,nk2))
 ABI_MALLOC(wtk,(nk2))
 ABI_MALLOC(eig,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(occ,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(cg,(2,orbs%mpw*orbs%nspinor,orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(added,(nk2))
 ABI_MALLOC(tr_new,(nk2))

 nband(1:nk1,:) = orbs%nband
 npw(1:nk1) = orbs%npw
 kg(:,:,1:nk1) = orbs%kg
 kpt(:,1:nk1) = orbs%kpt
 eig(:,1:nk1,:) = orbs%eig
 occ(:,1:nk1,:) = orbs%occ
 cg(:,:,:,1:nk1,:) = orbs%cg
 added(1:nk1) = .false.
 do ik=1,nk1
   nband(nk1+ik,:) = orbs%nband(ik,:)
   npw(nk1+ik) = orbs%npw(ik)
   kg(:,:,nk1+ik) = -orbs%kg(:,:,ik)
   kpt(:,nk1+ik) = -orbs%kpt(:,ik)
   eig(:,nk1+ik,:) = orbs%eig(:,ik,:)
   occ(:,nk1+ik,:) = orbs%occ(:,ik,:)
   cg(1,:,:,nk1+ik,:) = orbs%cg(1,:,:,ik,:)
   cg(2,:,:,nk1+ik,:) = -orbs%cg(2,:,:,ik,:)
   added(nk1+ik) = .true.
   tr_new(ik) = nk1+ik
   tr_new(nk1+ik) = ik
 end do
 wtk = one/real(nk2,dp)

 call move_alloc(nband,orbs%nband)
 call move_alloc(npw,orbs%npw)
 call move_alloc(kg,orbs%kg)
 call move_alloc(kpt,orbs%kpt)
 call move_alloc(wtk,orbs%wtk)
 call move_alloc(eig,orbs%eig)
 call move_alloc(occ,orbs%occ)
 call move_alloc(cg,orbs%cg)
 call move_alloc(added,orbs%added)
 call move_alloc(tr_new,orbs%tr_k)
 orbs%nkpt = nk2
 nadded = nk1

end subroutine rdmft_orbs_complete_time_reversal
