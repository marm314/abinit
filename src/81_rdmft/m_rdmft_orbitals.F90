!!****f* m_rdmft_orbitals/rdmft_orbs_align_time_reversal
!! NAME
!!  rdmft_orbs_align_time_reversal
!!
!! FUNCTION
!!  For every pair (k,-k) of the mesh, replace the orbitals of the k-point with the larger index by the time-reversed
!!  orbitals of the other one, c_{n,-k}(G) = conjg(c_{n,k}(-G)), and its eigenvalues by the ones of k. This fixes the
!!  arbitrary choice of the orbitals within degenerate shells at -k made by the diagonalization, which would break the
!!  band-by-band correspondence assumed by the rotations (conjugate matrix at -k) and by the ties of the occupations.
!!
!! OUTPUT
!!  naligned = number of k-points whose orbitals were replaced
!!
!! SOURCE
subroutine rdmft_orbs_align_time_reversal(orbs,naligned)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: naligned

 !Local variables-------------------------------
 !scalars
 integer :: ib,ie,ig,ik,ish,jb,jk,kb,mg,nacc,nb,ng1,key,m
 integer :: rr(3)
 real(dp) :: nrm
 complex(dpc),allocatable :: cand(:,:),acc(:,:)
 integer,allocatable :: pidx(:)
 !arrays
 integer,allocatable :: lookup(:)

! *************************************************************************

 naligned = 0
 mg = max(maxval(abs(orbs%kg)),1)+2
 ng1 = 2*mg+1
 ABI_MALLOC(lookup,(ng1**3))
 do ik=1,orbs%nkpt
   jk = orbs%tr_k(ik)
   if (jk <= ik) cycle
   if (orbs%npw(jk) /= orbs%npw(ik) .or. any(orbs%nband(jk,:) /= orbs%nband(ik,:))) cycle
   ! k_jk = -k_ik + rr: the vector G' of -k corresponds to G = -G' - rr of k
   rr = nint(orbs%kpt(:,ik)+orbs%kpt(:,jk))
   ! position of each vector G of the k-point ik
   lookup = 0
   do ig=1,orbs%npw(ik)
     key = 1+(orbs%kg(1,ig,ik)+mg)+ng1*((orbs%kg(2,ig,ik)+mg)+ng1*(orbs%kg(3,ig,ik)+mg))
     lookup(key) = ig
   end do
   nb = orbs%nband(ik,1)
   do ig=1,orbs%npw(jk)
     key = 1+(-orbs%kg(1,ig,jk)-rr(1)+mg)+ng1*((-orbs%kg(2,ig,jk)-rr(2)+mg)+ng1*(-orbs%kg(3,ig,jk)-rr(3)+mg))
     if (lookup(key) == 0) then
       ABI_ERROR('RDMFT: the plane-wave sets at k and -k are not related by G -> -G.')
     end if
   end do
   do ig=1,orbs%npw(jk)
     key = 1+(-orbs%kg(1,ig,jk)-rr(1)+mg)+ng1*((-orbs%kg(2,ig,jk)-rr(2)+mg)+ng1*(-orbs%kg(3,ig,jk)-rr(3)+mg))
     do ib=1,nb
       orbs%cg(1,ig,ib,jk,1) = orbs%cg(1,lookup(key),ib,ik,1)
       orbs%cg(2,ig,ib,jk,1) = -orbs%cg(2,lookup(key),ib,ik,1)
     end do
   end do
   orbs%eig(1:nb,jk,1) = orbs%eig(1:nb,ik,1)
   naligned = naligned+1
 end do

 ! Time-reversal-invariant k-points (k = -k + G): the rotations are real there, so the bands must be real functions
 ! (c(-G-rr) = conjg(c(G))), also inside the degenerate shells: build real orthonormal combinations of each shell
 do ik=1,orbs%nkpt
   if (orbs%tr_k(ik) /= ik) cycle
   nb = orbs%nband(ik,1)
   rr = nint(orbs%kpt(:,ik)+orbs%kpt(:,ik))
   lookup = 0
   do ig=1,orbs%npw(ik)
     key = 1+(orbs%kg(1,ig,ik)+mg)+ng1*((orbs%kg(2,ig,ik)+mg)+ng1*(orbs%kg(3,ig,ik)+mg))
     lookup(key) = ig
   end do
   ABI_MALLOC(pidx,(orbs%npw(ik)))
   do ig=1,orbs%npw(ik)
     key = 1+(-orbs%kg(1,ig,ik)-rr(1)+mg)+ng1*((-orbs%kg(2,ig,ik)-rr(2)+mg)+ng1*(-orbs%kg(3,ig,ik)-rr(3)+mg))
     pidx(ig) = lookup(key)
     if (pidx(ig) == 0) then
       ABI_ERROR('RDMFT: the plane-wave set at a time-reversal-invariant k-point is not symmetric under G -> -G.')
     end if
   end do
   ib = 1
   do while (ib <= nb)
     ie = ib
     do while (ie < nb)
       if (abs(orbs%eig(ie+1,ik,1)-orbs%eig(ie,ik,1)) > 1.0e-6_dp) exit
       ie = ie+1
     end do
     m = ie-ib+1
     ABI_MALLOC(cand,(orbs%npw(ik),2*m))
     ABI_MALLOC(acc,(orbs%npw(ik),m))
     do jb=ib,ie
       do ig=1,orbs%npw(ik)
         cand(ig,2*(jb-ib)+1) = cmplx(orbs%cg(1,ig,jb,ik,1),orbs%cg(2,ig,jb,ik,1),kind=dpc)+ &
                                cmplx(orbs%cg(1,pidx(ig),jb,ik,1),-orbs%cg(2,pidx(ig),jb,ik,1),kind=dpc)
         cand(ig,2*(jb-ib)+2) = -cmplx(zero,one,kind=dpc)*(cmplx(orbs%cg(1,ig,jb,ik,1),orbs%cg(2,ig,jb,ik,1),kind=dpc)- &
                                cmplx(orbs%cg(1,pidx(ig),jb,ik,1),-orbs%cg(2,pidx(ig),jb,ik,1),kind=dpc))
       end do
     end do
     ! real Gram-Schmidt: keep m independent vectors
     nacc = 0
     do kb=1,2*m
       if (nacc == m) exit
       do ish=1,2
         do jb=1,nacc
           nrm = sum(real(conjg(acc(:,jb))*cand(:,kb),dp))
           cand(:,kb) = cand(:,kb)-nrm*acc(:,jb)
         end do
       end do
       nrm = sqrt(sum(real(cand(:,kb))**2+aimag(cand(:,kb))**2))
       if (nrm > 1.0e-6_dp) then
         nacc = nacc+1
         acc(:,nacc) = cand(:,kb)/nrm
       end if
     end do
     if (nacc /= m) then
       ABI_ERROR('RDMFT: cannot build a real basis of a degenerate shell at a time-reversal-invariant k-point.')
     end if
     do jb=ib,ie
       orbs%cg(1,1:orbs%npw(ik),jb,ik,1) = real(acc(:,jb-ib+1),dp)
       orbs%cg(2,1:orbs%npw(ik),jb,ik,1) = aimag(acc(:,jb-ib+1))
     end do
     ABI_FREE(cand)
     ABI_FREE(acc)
     ib = ie+1
   end do
   ABI_FREE(pidx)
   naligned = naligned+1
 end do
 ABI_FREE(lookup)

end subroutine rdmft_orbs_align_time_reversal
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_expand_ibz
!! NAME
!!  rdmft_orbs_expand_ibz
!!
!! FUNCTION
!!  If the ground-state WFK holds the irreducible BZ (kptopt 1 or 4 with more than one symmetry operation), expand the
!!  orbitals to the full k-point mesh with the symmetry operations of the ground state (rotation of the plane-wave
!!  coefficients: permutation of the G vectors and phases of the non-symmorphic translations, complex conjugation for time
!!  reversal). The k-point mesh is then the full BZ with uniform weights, as a ground-state calculation with kptopt 3.
!!  The orbital (n,-k) is built as the exact conjugate of (n,k): c_{n,-k}(G) = conjg(c_{n,k}(-G)).
!!  The orbitals of a star are the images of the ones of the representative (star_rep) with the same band index, so a
!!  rotation of the bands of the representative can be applied to the whole star (star_conj marks the antiunitary images).
!!
!! OUTPUT
!!  nexp = number of k-points of the expanded mesh (0 if the WFK does not hold an irreducible BZ: nothing is done)
!!
!! SOURCE
subroutine rdmft_orbs_expand_ibz(orbs,nexp)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: nexp

 !Local variables-------------------------------
 !scalars
 integer,parameter :: kptopt3=3
 integer :: ii,ikf,ik_ibz,isym,itimrev,jk,mband,nkbz,nkibz,npw1,npw2,nbnd,nstar,timrev
 real(dp) :: dksqmax
 character(len=500) :: msg
 type(crystal_t) :: cryst
 !arrays
 integer :: g0(3),gmax(3),gmax2(3),work_ngfft(18)
 integer,allocatable :: bz2ibz(:,:),kg2(:,:),ptr(:),npw(:),nband(:,:),kg(:,:,:),srep(:)
 logical,allocatable :: done(:),sconj(:),abs_conj(:)
 real(dp) :: kt(3)
 real(dp),allocatable :: kbz(:,:),kibz(:,:),wtk(:),work(:,:,:,:),cgk(:,:,:,:,:),eig(:,:,:),occ(:,:,:),kpt(:,:)

! *************************************************************************

 nexp = 0
 if (orbs%hdr%nsym <= 1) return
 if (orbs%hdr%kptopt /= 1 .and. orbs%hdr%kptopt /= 4) return

 cryst = orbs%hdr%get_crystal()
 timrev = kpts_timrev_from_kptopt(orbs%hdr%kptopt)

 !Full mesh of the ground-state calculation (kptopt 3) and map onto the irreducible k-points of the file
 call kpts_ibz_from_kptrlatt(cryst,orbs%hdr%kptrlatt,kptopt3,orbs%hdr%nshiftk,orbs%hdr%shiftk,nkibz,kibz,wtk,nkbz,kbz)
 ABI_FREE(kibz)
 ABI_FREE(wtk)
 ABI_MALLOC(bz2ibz,(nkbz,6))
 call listkk(dksqmax,cryst%gmet,bz2ibz,orbs%kpt,kbz,orbs%nkpt,nkbz,cryst%nsym,1,cryst%symafm,cryst%symrel,timrev,&
             xmpi_comm_self,use_symrec=.False.)
 if (dksqmax > tol12) then
   write(msg,'(3a,es14.6,2a)') 'RDMFT: the k-points of the ground-state WFK cannot generate the full k-point mesh with its',&
     ' symmetry operations.',ch10,dksqmax,ch10,'Action: check kptopt, ngkpt, shiftk and nsym of the ground-state calculation.'
   ABI_ERROR(msg)
 end if

 mband = orbs%mband
 !Time-reversal partner (-k) of each k-point of the full mesh
 ABI_MALLOC(ptr,(nkbz))
 ptr = 0
 do ikf=1,nkbz
   do jk=1,nkbz
     kt(:) = kbz(:,ikf)+kbz(:,jk)
     if (maxval(abs(kt(:)-anint(kt(:)))) < 1.0e-6_dp) then
       ptr(ikf) = jk
       exit
     end if
   end do
 end do

 ABI_MALLOC(npw,(nkbz))
 ABI_MALLOC(nband,(nkbz,orbs%nsppol))
 ABI_MALLOC(kpt,(3,nkbz))
 ABI_MALLOC(eig,(mband,nkbz,orbs%nsppol))
 ABI_MALLOC(occ,(mband,nkbz,orbs%nsppol))
 ABI_MALLOC(done,(nkbz))
 ABI_MALLOC(srep,(nkbz))
 ABI_MALLOC(abs_conj,(nkbz))
 ABI_MALLOC(sconj,(nkbz))
 done = .false.
 srep = 0
 abs_conj = .false.
 npw = 0
 eig = zero
 occ = zero
 !Plane waves of every point: same number as at the irreducible one (the sphere is invariant under the operations)
 do ikf=1,nkbz
   npw(ikf) = orbs%npw(bz2ibz(ikf,1))
   nband(ikf,:) = orbs%nband(bz2ibz(ikf,1),:)
 end do
 ABI_MALLOC(kg,(3,orbs%mpw,nkbz))
 ABI_MALLOC(cgk,(2,orbs%mpw*orbs%nspinor,mband,nkbz,orbs%nsppol))
 kg = 0
 cgk = zero

 nstar = 0
 do ikf=1,nkbz
   if (done(ikf)) cycle
   ik_ibz = bz2ibz(ikf,1)
   isym = bz2ibz(ikf,2)
   itimrev = bz2ibz(ikf,6)
   g0 = bz2ibz(ikf,3:5)
   npw1 = orbs%npw(ik_ibz)
   call get_kg(kbz(:,ikf),1,orbs%hdr%ecut_eff,cryst%gmet,npw2,kg2)
   if (npw2 /= npw1) then
     write(msg,'(a,i0,a,i0,a,i0)') 'RDMFT: the plane-wave sphere of the k-point ',ikf,' of the full mesh has ',npw2,&
       ' plane waves, the one of its irreducible k-point ',npw1
     ABI_ERROR(msg)
   end if
   gmax = maxval(abs(orbs%kg(:,1:npw1,ik_ibz)),dim=2)
   gmax2 = maxval(abs(kg2),dim=2)
   gmax = 2*max(gmax,gmax2)+1
   call ngfft_seq(work_ngfft,gmax)
   ABI_MALLOC(work,(2,work_ngfft(4),work_ngfft(5),work_ngfft(6)))
   work = zero
   kpt(:,ikf) = kbz(:,ikf)
   kg(:,1:npw2,ikf) = kg2
   do ii=1,orbs%nsppol
     nbnd = nband(ikf,ii)
     call cgtk_rotate(cryst,orbs%kpt(:,ik_ibz),isym,itimrev,g0,orbs%nspinor,nbnd,npw1,orbs%kg(:,1:npw1,ik_ibz),npw2,kg2,1,1,&
                      orbs%cg(:,1:npw1*orbs%nspinor,1:nbnd,ik_ibz,ii),cgk(:,1:npw2*orbs%nspinor,1:nbnd,ikf,ii),work_ngfft,work)
     eig(1:nbnd,ikf,ii) = orbs%eig(1:nbnd,ik_ibz,ii)
     occ(1:nbnd,ikf,ii) = orbs%occ(1:nbnd,ik_ibz,ii)
   end do
   ABI_FREE(work)
   ABI_FREE(kg2)
   done(ikf) = .true.
   abs_conj(ikf) = (itimrev == 1)
   nstar = nstar+1
   !The partner -k as the exact conjugate (same irreducible k-point, antiunitary relation to the representative)
   jk = ptr(ikf)
   if (jk > 0 .and. jk /= ikf .and. .not.done(jk) .and. bz2ibz(jk,1) == ik_ibz) then
     kpt(:,jk) = -kbz(:,ikf)
     npw(jk) = npw(ikf)
     nband(jk,:) = nband(ikf,:)
     kg(:,1:npw(ikf),jk) = -kg(:,1:npw(ikf),ikf)
     cgk(1,:,:,jk,:) = cgk(1,:,:,ikf,:)
     cgk(2,:,:,jk,:) = -cgk(2,:,:,ikf,:)
     eig(:,jk,:) = eig(:,ikf,:)
     occ(:,jk,:) = occ(:,ikf,:)
     done(jk) = .true.
     abs_conj(jk) = .not.abs_conj(ikf)
   end if
 end do

 !Representative of each star: the first k-point generated from each irreducible k-point; conjugation relative to it
 srep = 0
 do ikf=1,nkbz
   ik_ibz = bz2ibz(ikf,1)
   do jk=1,ikf
     if (bz2ibz(jk,1) == ik_ibz) then
       srep(ikf) = jk
       exit
     end if
   end do
   sconj(ikf) = (abs_conj(ikf) .neqv. abs_conj(srep(ikf)))
 end do

 !Replace the arrays of the object
 call move_alloc(npw,orbs%npw)
 call move_alloc(nband,orbs%nband)
 call move_alloc(kg,orbs%kg)
 call move_alloc(kpt,orbs%kpt)
 call move_alloc(eig,orbs%eig)
 call move_alloc(occ,orbs%occ)
 call move_alloc(cgk,orbs%cg)
 ABI_SFREE(orbs%wtk)
 ABI_MALLOC(orbs%wtk,(nkbz))
 orbs%wtk = one/real(nkbz,dp)
 ABI_SFREE(orbs%added)
 ABI_MALLOC(orbs%added,(nkbz))
 orbs%added = .false.
 ABI_SFREE(orbs%ibz_rep)
 ABI_SFREE(orbs%ibz_conj)
 ABI_SFREE(orbs%star_rep)
 ABI_SFREE(orbs%star_conj)
 call move_alloc(srep,orbs%ibz_rep)
 call move_alloc(sconj,orbs%ibz_conj)
 orbs%nkpt = nkbz
 call orbs%find_tr_partners()
 nexp = nkbz

 write(msg,'(3a,i0,a,i0,a,i0,a)') ch10,' RDMFT: the ground-state WFK holds the irreducible BZ (',&
   'kptopt ',orbs%hdr%kptopt,'): ',orbs%hdr%nkpt,' k-points expanded to ',nkbz,&
   ' k-points of the full BZ with the symmetry operations'
 call wrtout([ab_out,std_out],msg)
 write(msg,'(a,i0,a,i0,a)') '        (',orbs%hdr%nsym,' symmetry operations, ',nstar,&
   ' k-points obtained by rotation, the rest by time reversal)'
 call wrtout([ab_out,std_out],msg)

 ABI_FREE(kbz)
 ABI_FREE(bz2ibz)
 ABI_FREE(ptr)
 ABI_FREE(done)
 ABI_FREE(abs_conj)
 call cryst%free()

end subroutine rdmft_orbs_expand_ibz
