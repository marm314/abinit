!!****t* m_rdmft_orbitals/rdmft_orbs_t
!! NAME
!! rdmft_orbs_t
!!
!! FUNCTION
!!  Ground-state Bloch orbitals read from a WFK file.
!!
!! SOURCE

 type,public :: rdmft_orbs_t

   integer :: nkpt = 0
   ! Number of k-points.

   integer :: nsppol = 0
   ! Number of spin polarizations.

   integer :: nspinor = 0
   ! Number of spinor components.

   integer :: mband = 0
   ! Maximum number of bands over k-points.

   real(dp) :: ecut = zero
   ! ecut (input variable) of the ground-state calculation that wrote the WFK file.

   integer :: mpw = 0
   ! Maximum number of plane waves over k-points.

   real(dp) :: nelect = zero
   ! Number of electrons.

   real(dp) :: ucvol = zero
   ! Volume of the unit cell (Bohr^3).

   real(dp) :: rprimd(3,3) = zero
   ! Real space primitive translations (Bohr).

   real(dp) :: gmet(3,3) = zero
   ! Metric tensor in reciprocal space (Bohr^-2).

   integer,allocatable :: nband(:,:)
   ! nband(nkpt,nsppol)
   ! Number of bands at each k-point and spin.

   integer,allocatable :: npw(:)
   ! npw(nkpt)
   ! Number of plane waves at each k-point.

   integer,allocatable :: kg(:,:,:)
   ! kg(3,mpw,nkpt)
   ! Reduced coordinates of the plane waves at each k-point.

   real(dp),allocatable :: kpt(:,:)
   ! kpt(3,nkpt)
   ! Reduced coordinates of the k-points.

   real(dp),allocatable :: wtk(:)
   ! wtk(nkpt)
   ! Weights of the k-points (normalized to one).

   real(dp),allocatable :: eig(:,:,:)
   ! eig(mband,nkpt,nsppol)
   ! Eigenvalues (Hartree).

   real(dp),allocatable :: occ(:,:,:)
   ! occ(mband,nkpt,nsppol)
   ! Occupation numbers of the ground-state calculation (between 0 and 2/nsppol/nspinor).

   real(dp),allocatable :: cg(:,:,:,:,:)
   ! cg(2,mpw*nspinor,mband,nkpt,nsppol)
   ! Plane-wave coefficients, normalized to one for each band.

   integer,allocatable :: tr_k(:)
   ! tr_k(nkpt)
   ! Index of the k-point equal to -k modulo a reciprocal lattice vector (itself for the time-reversal-invariant
   ! k-points), 0 if -k is not in the mesh.

   logical,allocatable :: added(:)
   ! added(nkpt)
   ! True for the k-points generated by time reversal (complete_time_reversal).

   type(hdr_type) :: hdr
   ! Header of the WFK file that was read (template of the header of the WFK/DEN files written at the end).

 contains

   procedure :: free => rdmft_orbs_free
   ! Free memory.

   procedure :: read_wfk => rdmft_orbs_read_wfk
   ! Read the orbitals from a WFK file.

   procedure :: check_orthonormality => rdmft_orbs_check_orthonormality
   ! Compute the maximum deviation from orthonormality.

   procedure :: find_tr_partners => rdmft_orbs_find_tr_partners
   ! Find the k-point -k of every k-point of the mesh.

   procedure :: complete_time_reversal => rdmft_orbs_complete_time_reversal
   procedure :: align_time_reversal => rdmft_orbs_align_time_reversal
   procedure :: complete_basis => rdmft_orbs_complete_basis
   ! Add the missing -k points, with the time-reversed orbitals.

   procedure :: rotate_pair => rdmft_orbs_rotate_pair
   procedure :: rotate_k => rdmft_orbs_rotate_k
   ! Rotate two bands of one k-point.

   procedure :: make_hdr => rdmft_orbs_make_hdr
   ! Header of the WFK/DEN files for the current k-points, bands and occupations.

   procedure :: write_wfk => rdmft_orbs_write_wfk
   ! Write the orbitals, eigenvalues and occupations to a WFK file.

   procedure :: tr_alignment => rdmft_orbs_tr_alignment
   ! Deviation of the orbitals at -k from the time-reversed ones of k.

 end type rdmft_orbs_t
!!***

 public :: rdmft_rot_matrix
!!***

