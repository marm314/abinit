!!****f* m_rdmft_orbitals/rdmft_orbs_read_wfk
!! NAME
!!  rdmft_orbs_read_wfk
!!
!! FUNCTION
!!  Read the orbitals, eigenvalues and occupations of all k-points from a WFK file.
!!
!! INPUTS
!!  wfk_path = path of the WFK file (Fortran or netcdf format)
!!
!! OUTPUT
!!  orbs <type(rdmft_orbs_t)> = the orbitals (allocated here)
!!
!! SOURCE
subroutine rdmft_orbs_read_wfk(orbs,wfk_path)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 character(len=*),intent(in) :: wfk_path

 !Local variables-------------------------------
 !scalars
 integer,parameter :: formeig0=0
 integer :: ik,isppol,nb,npw_k,sc_mode
 character(len=500) :: msg
 type(hdr_type) :: hdr
 type(wfk_t) :: wfk
 !arrays
 integer :: band_block(2)
 integer,allocatable :: kg_k(:,:)
 real(dp) :: gprimd(3,3),rmet(3,3)
 real(dp),allocatable :: cg_k(:,:),eig_k(:),occ_k(:)

! *************************************************************************

 call orbs%free()

 call wfk%open_read(wfk_path,formeig0,iomode_from_fname(wfk_path),get_unit(),xmpi_comm_self,hdr_out=hdr)

 if (hdr%usepaw /= 0) then
   ABI_ERROR('RDMFT: PAW is not yet supported.')
 end if
 if (hdr%nspinor /= 1) then
   ABI_ERROR('RDMFT: nspinor=1 is required.')
 end if
 if (hdr%nsppol /= 1) then
   ABI_ERROR('RDMFT: nsppol=1 is required (closed-shell).')
 end if
 if (any(hdr%istwfk(:) /= 1)) then
   ABI_ERROR('RDMFT: istwfk=1 is required at all k-points (use istwfk *1 in the ground-state calculation).')
 end if

 orbs%nkpt = hdr%nkpt
 orbs%nsppol = hdr%nsppol
 orbs%nspinor = hdr%nspinor
 orbs%mband = maxval(hdr%nband)
 orbs%mpw = maxval(hdr%npwarr)
 orbs%nelect = hdr%nelect
 orbs%ecut = hdr%ecut
 orbs%rprimd(:,:) = hdr%rprimd(:,:)
 call metric(orbs%gmet,gprimd,-1,rmet,orbs%rprimd,orbs%ucvol)

 ABI_MALLOC(orbs%nband,(orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%npw,(orbs%nkpt))
 ABI_MALLOC(orbs%kg,(3,orbs%mpw,orbs%nkpt))
 ABI_MALLOC(orbs%kpt,(3,orbs%nkpt))
 ABI_MALLOC(orbs%wtk,(orbs%nkpt))
 ABI_MALLOC(orbs%eig,(orbs%mband,orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%occ,(orbs%mband,orbs%nkpt,orbs%nsppol))
 ABI_MALLOC(orbs%cg,(2,orbs%mpw*orbs%nspinor,orbs%mband,orbs%nkpt,orbs%nsppol))

 orbs%nband = 0
 orbs%kg = 0
 orbs%eig = zero
 orbs%occ = zero
 orbs%cg = zero
 orbs%npw(:) = hdr%npwarr(:)
 orbs%kpt(:,:) = hdr%kptns(:,:)
 orbs%wtk(:) = hdr%wtk(:)/sum(hdr%wtk)

 sc_mode = xmpio_single
 do isppol=1,orbs%nsppol
   do ik=1,orbs%nkpt
     nb = hdr%nband(ik+(isppol-1)*orbs%nkpt)
     orbs%nband(ik,isppol) = nb
     npw_k = orbs%npw(ik)
     band_block = [1,nb]

     ABI_MALLOC(kg_k,(3,npw_k))
     ABI_MALLOC(cg_k,(2,npw_k*orbs%nspinor*nb))
     ABI_MALLOC(eig_k,(wfk%mband))
     ABI_MALLOC(occ_k,(wfk%mband))

     call wfk%read_band_block(band_block,ik,isppol,sc_mode,kg_k=kg_k,cg_k=cg_k,eig_k=eig_k,occ_k=occ_k)

     orbs%kg(:,1:npw_k,ik) = kg_k(:,:)
     orbs%cg(:,1:npw_k*orbs%nspinor,1:nb,ik,isppol) = reshape(cg_k,[2,npw_k*orbs%nspinor,nb])
     orbs%eig(1:nb,ik,isppol) = eig_k(1:nb)
     orbs%occ(1:nb,ik,isppol) = occ_k(1:nb)

     ABI_FREE(kg_k)
     ABI_FREE(cg_k)
     ABI_FREE(eig_k)
     ABI_FREE(occ_k)
   end do
 end do

 call wfk%close()
 call hdr%copy(orbs%hdr)
 call hdr%free()

 ABI_MALLOC(orbs%added,(orbs%nkpt))
 orbs%added = .false.
 call orbs%find_tr_partners()

 write(msg,'(3a,i0,a,i0,a,i0,a,i0,a)') ' RDMFT: orbitals read from ',trim(wfk_path),ch10,&
   orbs%nkpt,' k-points, ',orbs%mband,' bands, up to ',orbs%mpw,' plane waves, nelect = ',nint(orbs%nelect),ch10
 call wrtout([ab_out,std_out],msg)

end subroutine rdmft_orbs_read_wfk
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_make_hdr
!! NAME
!!  rdmft_orbs_make_hdr
!!
!! FUNCTION
!!  Header of the WFK/DEN files written at the end of the run: the header of the ground-state WFK file with the k-points
!!  (completed by time reversal), numbers of bands (completed basis), plane waves and occupations of the current orbitals.
!!
!! INPUTS
!!  occ(mband,nkpt)= occupation numbers (spin summed, between 0 and 2)
!!
!! SOURCE

subroutine rdmft_orbs_make_hdr(orbs,hdr,occ)

 !Arguments ------------------------------------
 class(rdmft_orbs_t),intent(in) :: orbs
 type(hdr_type),intent(out) :: hdr
 real(dp),intent(in) :: occ(:,:)

 !Local variables-------------------------------
 integer :: ik,ib0,nb

! *************************************************************************

 call orbs%hdr%copy(hdr)
 if (hdr%nkpt /= orbs%nkpt) hdr%kptopt = 0

 hdr%nkpt = orbs%nkpt
 hdr%bantot = sum(orbs%nband(:,1))
 hdr%mband = maxval(orbs%nband(:,1))

 ABI_SFREE(hdr%istwfk)
 ABI_SFREE(hdr%nband)
 ABI_SFREE(hdr%npwarr)
 ABI_SFREE(hdr%kptns)
 ABI_SFREE(hdr%wtk)
 ABI_SFREE(hdr%occ)
 ABI_MALLOC(hdr%istwfk,(orbs%nkpt))
 ABI_MALLOC(hdr%nband,(orbs%nkpt))
 ABI_MALLOC(hdr%npwarr,(orbs%nkpt))
 ABI_MALLOC(hdr%kptns,(3,orbs%nkpt))
 ABI_MALLOC(hdr%wtk,(orbs%nkpt))
 ABI_MALLOC(hdr%occ,(hdr%bantot))
 hdr%istwfk = 1
 hdr%nband(:) = orbs%nband(:,1)
 hdr%npwarr(:) = orbs%npw(:)
 hdr%kptns(:,:) = orbs%kpt(:,:)
 hdr%wtk(:) = orbs%wtk(:)
 ib0 = 0
 do ik=1,orbs%nkpt
   nb = orbs%nband(ik,1)
   hdr%occ(ib0+1:ib0+nb) = occ(1:nb,ik)
   ib0 = ib0+nb
 end do

end subroutine rdmft_orbs_make_hdr
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_write_wfk
!! NAME
!!  rdmft_orbs_write_wfk
!!
!! FUNCTION
!!  Write the current orbitals to a WFK file (to be called by one process only).
!!
!! INPUTS
!!  fname= path of the file (".nc" appended for the netcdf format)
!!  iomode= I/O mode (dtset%iomode)
!!  hdr= header (rdmft_orbs_make_hdr)
!!  eig(mband,nkpt)= eigenvalues to store
!!  occ(mband,nkpt)= occupation numbers to store (between 0 and 2)
!!
!! SOURCE

subroutine rdmft_orbs_write_wfk(orbs,fname,iomode,hdr,eig,occ)

 !Arguments ------------------------------------
 class(rdmft_orbs_t),intent(in) :: orbs
 character(len=*),intent(in) :: fname
 integer,intent(in) :: iomode
 type(hdr_type),intent(in) :: hdr
 real(dp),intent(in) :: eig(:,:),occ(:,:)

 !Local variables-------------------------------
 integer,parameter :: formeig0=0
 integer :: ik,nb,npw_k
 character(len=fnlen) :: path
 type(wfk_t) :: wfk
 real(dp),allocatable :: cg_k(:,:),eig_k(:),occ_k(:)

! *************************************************************************

 path = fname
 if (iomode == IO_MODE_ETSF) path = nctk_ncify(fname)
 call wfk%open_write(hdr,path,formeig0,iomode,get_unit(),xmpi_comm_self)

 do ik=1,orbs%nkpt
   nb = orbs%nband(ik,1)
   npw_k = orbs%npw(ik)
   ABI_MALLOC(cg_k,(2,npw_k*nb))
   ABI_MALLOC(eig_k,(nb))
   ABI_MALLOC(occ_k,(nb))
   cg_k = reshape(orbs%cg(:,1:npw_k,1:nb,ik,1),[2,npw_k*nb])
   eig_k = eig(1:nb,ik)
   occ_k = occ(1:nb,ik)
   call wfk%write_band_block([1,nb],ik,1,xmpio_single,kg_k=orbs%kg(:,1:npw_k,ik),cg_k=cg_k,eig_k=eig_k,occ_k=occ_k)
   ABI_FREE(cg_k)
   ABI_FREE(eig_k)
   ABI_FREE(occ_k)
 end do

 call wfk%close()

end subroutine rdmft_orbs_write_wfk
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_find_tr_partners
!! NAME
!!  rdmft_orbs_find_tr_partners
!!
!! FUNCTION
!!  Find for every k-point the k-point equal to -k modulo a reciprocal lattice vector (tr_k, 0 if absent).
!!
!! SOURCE
subroutine rdmft_orbs_find_tr_partners(orbs)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs

 !Local variables-------------------------------
 !scalars
 integer :: ik,jk
 !arrays
 real(dp) :: kt(3)

! *************************************************************************

 ABI_SFREE(orbs%tr_k)
 ABI_MALLOC(orbs%tr_k,(orbs%nkpt))
 orbs%tr_k = 0
 do ik=1,orbs%nkpt
   do jk=1,orbs%nkpt
     kt(:) = orbs%kpt(:,ik)+orbs%kpt(:,jk)
     if (maxval(abs(kt(:)-anint(kt(:)))) < 1.0e-6_dp) then
       orbs%tr_k(ik) = jk
       exit
     end if
   end do
 end do

end subroutine rdmft_orbs_find_tr_partners
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_complete_basis
!! NAME
!!  rdmft_orbs_complete_basis
!!
!! FUNCTION
!!  Complete the set of bands of every k-point to all its plane waves (nband = npw): the bands read are kept, and the
!!  others are orthonormal vectors of the orthogonal complement, built from plane waves with a pivoted Gram-Schmidt
!!  procedure (largest residual first). The added bands have occupation 0 and an arbitrary (large) energy.
!!  This gives a complete basis of rotations of the orbitals, to test the optimization of the orbitals against the
!!  basis-set limit (for example, that the single-determinant functional reaches the Hartree-Fock energy).
!!
!! OUTPUT
!!  nadded = total number of bands added
!!
!! SOURCE
subroutine rdmft_orbs_complete_basis(orbs,nadded)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: nadded

 !Local variables-------------------------------
 !scalars
 integer :: ib,ig,ii,ik,ipiv,mnew,np,nb,pass
 real(dp) :: nrm
 complex(dpc) :: ov
 !arrays
 integer :: ipv(1)
 real(dp),allocatable :: cg(:,:,:,:,:),dres(:),eig(:,:,:),occ(:,:,:)
 complex(dpc),allocatable :: vec(:)

! *************************************************************************

 nadded = 0
 if (orbs%nspinor /= 1 .or. orbs%nsppol /= 1) then
   ABI_ERROR('RDMFT: rdmft_complete needs nsppol = 1 and nspinor = 1.')
 end if
 mnew = maxval(orbs%npw)
 ABI_MALLOC(cg,(2,orbs%mpw,mnew,orbs%nkpt,1))
 ABI_MALLOC(eig,(mnew,orbs%nkpt,1))
 ABI_MALLOC(occ,(mnew,orbs%nkpt,1))
 cg = zero
 eig = zero
 occ = zero
 ABI_MALLOC(vec,(orbs%mpw))
 ABI_MALLOC(dres,(orbs%mpw))
 do ik=1,orbs%nkpt
   nb = orbs%nband(ik,1)
   np = orbs%npw(ik)
   cg(:,:,1:nb,ik,1) = orbs%cg(:,:,1:nb,ik,1)
   eig(1:nb,ik,1) = orbs%eig(1:nb,ik,1)
   occ(1:nb,ik,1) = orbs%occ(1:nb,ik,1)
   do ig=1,np
     dres(ig) = one-sum(cg(1,ig,1:nb,ik,1)**2+cg(2,ig,1:nb,ik,1)**2)
   end do
   do ii=nb+1,np
     ipv = maxloc(dres(1:np))
     ipiv = ipv(1)
     vec = czero
     vec(ipiv) = cone
     do pass=1,2
       do ib=1,ii-1
         ov = czero
         do ig=1,np
           ov = ov+cmplx(cg(1,ig,ib,ik,1),-cg(2,ig,ib,ik,1),kind=dpc)*vec(ig)
         end do
         do ig=1,np
           vec(ig) = vec(ig)-ov*cmplx(cg(1,ig,ib,ik,1),cg(2,ig,ib,ik,1),kind=dpc)
         end do
       end do
     end do
     nrm = sqrt(sum(real(vec(1:np))**2+aimag(vec(1:np))**2))
     vec(1:np) = vec(1:np)/nrm
     cg(1,1:np,ii,ik,1) = real(vec(1:np),dp)
     cg(2,1:np,ii,ik,1) = aimag(vec(1:np))
     dres(1:np) = dres(1:np)-(real(vec(1:np))**2+aimag(vec(1:np))**2)
     eig(ii,ik,1) = 100.0_dp
     nadded = nadded+1
   end do
   orbs%nband(ik,1) = np
 end do
 ABI_FREE(vec)
 ABI_FREE(dres)
 call move_alloc(cg,orbs%cg)
 call move_alloc(eig,orbs%eig)
 call move_alloc(occ,orbs%occ)
 orbs%mband = mnew

end subroutine rdmft_orbs_complete_basis
