!!****f* m_rdmft_orbitals/rdmft_orbs_complete_time_reversal
!! NAME
!!  rdmft_orbs_complete_time_reversal
!!
!! FUNCTION
!!  Complete the k-point mesh so that it contains -k for every k. For a Monkhorst-Pack mesh either all the
!!  k-points have a partner or none (a mixed mesh is refused). The orbital of the added point -k is the complex
!!  conjugate of the one at k: c_{n,-k}(G) = conjg(c_{n,k}(-G)), i.e. the plane-wave list is -kg and the coefficients
!!  are conjugated; energies and occupations are the same. The mesh then has 2N points of weight 1/(2N).
!!
!! OUTPUT
!!  nadded = number of k-points added (0 if the mesh was already closed)
!!
!! SOURCE
subroutine rdmft_orbs_complete_time_reversal(orbs,nadded)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(out) :: nadded

 !Local variables-------------------------------
 !scalars
 integer :: ik,j,nk1,nk2
 !arrays
 integer,allocatable :: nband(:,:),npw(:),kg(:,:,:),tr_new(:),src(:)
 real(dp),allocatable :: kpt(:,:),wtk(:),eig(:,:,:),occ(:,:,:),cg(:,:,:,:,:)
 logical,allocatable :: added(:)

! *************************************************************************

 nadded = 0
 nk1 = orbs%nkpt
 ! k-points whose -k is not in the mesh (the time-reversal-invariant ones, tr_k = k, are their own partners)
 nadded = count(orbs%tr_k(:) == 0)
 if (nadded == 0) return
 if (any(orbs%tr_k(:) > 0 .and. orbs%tr_k(:) /= [(ik,ik=1,nk1)])) then
   nadded = 0
   ABI_ERROR('RDMFT: the k-point mesh has some k-points with -k and some without, the completion is not supported.')
 end if

 nk2 = nk1+nadded
 ABI_MALLOC(src,(nadded))
 j = 0
 do ik=1,nk1
   if (orbs%tr_k(ik) == 0) then
     j = j+1
     src(j) = ik
   end if
 end do
 ABI_MALLOC(nband,(nk2,orbs%nsppol))
 ABI_MALLOC(npw,(nk2))
 ABI_MALLOC(kg,(3,orbs%mpw,nk2))
 ABI_MALLOC(kpt,(3,nk2))
 ABI_MALLOC(wtk,(nk2))
 ABI_MALLOC(eig,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(occ,(orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(cg,(2,orbs%mpw*orbs%nspinor,orbs%mband,nk2,orbs%nsppol))
 ABI_MALLOC(added,(nk2))
 ABI_MALLOC(tr_new,(nk2))

 nband(1:nk1,:) = orbs%nband
 npw(1:nk1) = orbs%npw
 kg(:,:,1:nk1) = orbs%kg
 kpt(:,1:nk1) = orbs%kpt
 eig(:,1:nk1,:) = orbs%eig
 occ(:,1:nk1,:) = orbs%occ
 cg(:,:,:,1:nk1,:) = orbs%cg
 added(1:nk1) = .false.
 tr_new(1:nk1) = orbs%tr_k
 do j=1,nadded
   ik = src(j)
   nband(nk1+j,:) = orbs%nband(ik,:)
   npw(nk1+j) = orbs%npw(ik)
   kg(:,:,nk1+j) = -orbs%kg(:,:,ik)
   kpt(:,nk1+j) = -orbs%kpt(:,ik)
   eig(:,nk1+j,:) = orbs%eig(:,ik,:)
   occ(:,nk1+j,:) = orbs%occ(:,ik,:)
   cg(1,:,:,nk1+j,:) = orbs%cg(1,:,:,ik,:)
   cg(2,:,:,nk1+j,:) = -orbs%cg(2,:,:,ik,:)
   added(nk1+j) = .true.
   tr_new(ik) = nk1+j
   tr_new(nk1+j) = ik
 end do
 ! Uniform weights: the pairs (k,-k) have the same weight, and so do the time-reversal-invariant points
 wtk = one/real(nk2,dp)

 call move_alloc(nband,orbs%nband)
 call move_alloc(npw,orbs%npw)
 call move_alloc(kg,orbs%kg)
 call move_alloc(kpt,orbs%kpt)
 call move_alloc(wtk,orbs%wtk)
 call move_alloc(eig,orbs%eig)
 call move_alloc(occ,orbs%occ)
 call move_alloc(cg,orbs%cg)
 call move_alloc(added,orbs%added)
 call move_alloc(tr_new,orbs%tr_k)
 ABI_FREE(src)
 orbs%nkpt = nk2

end subroutine rdmft_orbs_complete_time_reversal
