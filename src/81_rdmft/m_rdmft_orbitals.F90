!!****f* m_rdmft_orbitals/rdmft_orbs_rotate_pair
!! NAME
!!  rdmft_orbs_rotate_pair
!!
!! FUNCTION
!!  Rotate the bands ib and jb of the k-point ik with the matrix U of rdmft_rot_matrix:
!!  psi'_ib = U_11 psi_ib + U_21 psi_jb, psi'_jb = U_12 psi_ib + U_22 psi_jb. The rotation mixes only states of
!!  the same k-point, so the Bloch character is kept.
!!
!! INPUTS
!!  ik, ib, jb = k-point and bands
!!  umat(2,2) = rotation matrix
!!
!! SOURCE
subroutine rdmft_orbs_rotate_pair(orbs,ik,ib,jb,umat)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(in) :: ik,ib,jb
 !arrays
 complex(dpc),intent(in) :: umat(2,2)

 !Local variables-------------------------------
 !scalars
 integer :: ig,npwso
 complex(dpc) :: cp,cq

! *************************************************************************

 npwso = orbs%npw(ik)*orbs%nspinor
 do ig=1,npwso
   cp = cmplx(orbs%cg(1,ig,ib,ik,1),orbs%cg(2,ig,ib,ik,1),kind=dpc)
   cq = cmplx(orbs%cg(1,ig,jb,ik,1),orbs%cg(2,ig,jb,ik,1),kind=dpc)
   orbs%cg(1,ig,ib,ik,1) = real(cp*umat(1,1)+cq*umat(2,1),dp)
   orbs%cg(2,ig,ib,ik,1) = aimag(cp*umat(1,1)+cq*umat(2,1))
   orbs%cg(1,ig,jb,ik,1) = real(cp*umat(1,2)+cq*umat(2,2),dp)
   orbs%cg(2,ig,jb,ik,1) = aimag(cp*umat(1,2)+cq*umat(2,2))
 end do

end subroutine rdmft_orbs_rotate_pair
!!***

!!****f* m_rdmft_orbitals/rdmft_orbs_rotate_k
!! NAME
!!  rdmft_orbs_rotate_k
!!
!! FUNCTION
!!  Rotate all the bands of the k-point ik with the unitary matrix U: psi'_j = sum_i psi_i U_ij.
!!  The rotation mixes only states of the same k-point, so the Bloch character is kept.
!!
!! INPUTS
!!  ik = k-point
!!  umat(nband,nband) = unitary matrix
!!
!! SOURCE
subroutine rdmft_orbs_rotate_k(orbs,ik,umat)

 !Arguments ------------------------------------
 !scalars
 class(rdmft_orbs_t),intent(inout) :: orbs
 integer,intent(in) :: ik
 !arrays
 complex(dpc),intent(in) :: umat(:,:)

 !Local variables-------------------------------
 !scalars
 integer :: ib,ig,jb,nb,npwso
 !arrays
 complex(dpc),allocatable :: cold(:,:),cnew(:)

! *************************************************************************

 nb = orbs%nband(ik,1)
 npwso = orbs%npw(ik)*orbs%nspinor
 ABI_MALLOC(cold,(nb,npwso))
 ABI_MALLOC(cnew,(nb))
 do ib=1,nb
   do ig=1,npwso
     cold(ib,ig) = cmplx(orbs%cg(1,ig,ib,ik,1),orbs%cg(2,ig,ib,ik,1),kind=dpc)
   end do
 end do
 do ig=1,npwso
   do jb=1,nb
     cnew(jb) = czero
     do ib=1,nb
       cnew(jb) = cnew(jb)+cold(ib,ig)*umat(ib,jb)
     end do
   end do
   do jb=1,nb
     orbs%cg(1,ig,jb,ik,1) = real(cnew(jb),dp)
     orbs%cg(2,ig,jb,ik,1) = aimag(cnew(jb))
   end do
 end do
 ABI_FREE(cold)
 ABI_FREE(cnew)

end subroutine rdmft_orbs_rotate_k
