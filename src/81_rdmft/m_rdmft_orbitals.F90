!!****t* m_rdmft_orbitals/rdmft_symtab_t
!! NAME
!! rdmft_symtab_t
!!
!! FUNCTION
!!  Classes of ordered pairs of k-points (k,k') under the symmetry operations of the ground state (unitary operations and
!!  their products with time reversal) that map the orbitals into the orbitals with the same band index. The Coulomb and
!!  exchange integrals J_pq and K_pq between the orbitals (n,k) and (m,k') are the same for all the pairs of a class, so
!!  only the representative pair of each class needs to be computed.
!!
!! SOURCE

 type,public :: rdmft_symtab_t

   integer :: ncls = 0
   ! Number of classes of ordered pairs of k-points.

   integer :: nops = 0
   ! Number of operations (unitary and antiunitary) that map the mesh onto itself.

   integer,allocatable :: cls(:,:)
   ! cls(nkpt,nkpt)
   ! Class of the ordered pair (k,k').

   integer,allocatable :: rep(:,:)
   ! rep(2,ncls)
   ! Representative pair of each class (the first in lexicographic order).

   integer,allocatable :: mptr(:)
   ! mptr(ncls+1)
   ! The members of the class c are mem(:,mptr(c):mptr(c+1)-1).

   integer,allocatable :: mem(:,:)
   ! mem(2,nkpt*nkpt)
   ! Members (pairs of k-points) of the classes.

   logical,allocatable :: use(:)
   ! use(ncls)
   ! The integrals of the class are computed (a class and its transposed one are equivalent: only one is computed).

   logical,allocatable :: selft(:)
   ! selft(ncls)
   ! The transposed pair (k',k) belongs to the same class: the band pairs (n,m) and (m,n) of the representative are equivalent.

   integer,allocatable :: kimg(:,:)
   ! kimg(nkpt,2*nsym)
   ! Image of each k-point by each operation (0 if the mesh is not invariant under the operation).

   logical,allocatable :: ok(:,:)
   ! ok(nkpt,2*nsym)
   ! The operation maps the orbital (n,k) onto (n,image) for all the bands n (up to a phase).

   logical,allocatable :: generic(:)
   ! generic(nkpt)
   ! Reducible k-point: the unitary operations that leave it unchanged are the identity only, or act on its bands with
   ! diagonal matrices (no degenerate shell forced by symmetry). The other k-points are kept as independent k-points
   ! (explicit pairs and rotations).

 contains

   procedure :: free => rdmft_symtab_free

 end type rdmft_symtab_t
